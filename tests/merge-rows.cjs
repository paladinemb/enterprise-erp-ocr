const assert = require('node:assert/strict');
const {parseText,exportRows} = require('../dist/core.js');
const XLSX = require('../dist/vendor/xlsx.full.min.js');
const rows = [['编号','名称'],['001',''],['',''],['003','轴承']];
assert.deepEqual(parseText(rows.map(row=>row.join('\t')).join('\n')),rows, 'blank cells and rows survive text rebuild');
assert.deepEqual(parseText(''),[]);
assert.deepEqual(parseText('名称  数量\n轴承  20'),[['名称','数量'],['轴承','20']]);
const combined = exportRows('采购申请单\n部门：设备部',rows,'制单 核批 承办');
assert.deepEqual(combined,[['采购申请单'],['部门：设备部'],[],...rows,[],['制单 核批 承办']]);
const workbook = XLSX.utils.book_new();
XLSX.utils.book_append_sheet(workbook,XLSX.utils.aoa_to_sheet(combined),'识别结果');
const restored = XLSX.read(XLSX.write(workbook,{type:'buffer',bookType:'xlsx'}),{type:'buffer'});
assert.equal(restored.Sheets['识别结果'].A5.v,'001');
assert.equal(restored.Sheets['识别结果'].A5.t,'s');
console.log('PASS: sections export in document order, blank rows, text rebuild, XLSX leading zeros');
